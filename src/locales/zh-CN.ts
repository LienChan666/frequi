const zhCNPatterns: ReadonlyArray<readonly [RegExp, string]> = [
  [/^Backtest running:\s*(.*)$/i, '回测运行中：$1'],
  [/^Backtest-result for\s+(.+)$/i, '$1 的回测结果'],
  [/^(\d+)\s+Trades?$/i, '$1 笔交易'],
  [/^Page\s+(\d+)\s+of\s+(\d+)$/i, '第 $1 / $2 页'],
  [/^Showing\s+(\d+)\s+to\s+(\d+)\s+of\s+(\d+)$/i, '显示第 $1–$2 条，共 $3 条'],
  [/^Selected:\s*(.*)$/i, '已选：$1'],
  [/^Bot:\s*(.*)$/i, '机器人：$1'],
  [/^Increasing position for\s+(.+)$/i, '增加 $1 的仓位'],
];

export function translateZhCN(value: string): string {
  const direct = zhCN[value];
  if (direct) return direct;

  for (const [pattern, replacement] of zhCNPatterns) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}
